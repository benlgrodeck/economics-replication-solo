const { PGlite } = await import(process.env.PGLITE_MODULE || '@electric-sql/pglite');
import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const db=new PGlite();
await db.exec(`create role anon; create role authenticated; create schema auth;
create table auth.users(id uuid primary key);
create function auth.uid() returns uuid language sql stable as $$select nullif(current_setting('test.uid',true),'')::uuid$$;
insert into auth.users values ('11111111-1111-4111-8111-111111111111'),('22222222-2222-4222-8222-222222222222');`);
await db.exec(readFileSync(root+'/backend/setup.sql','utf8'));
const questions=JSON.parse(readFileSync(root+'/studies.json','utf8'));
const answers=questions.map(q=>({id:q.id,choice:true,confidence:50}));
await db.exec(`set role authenticated; set test.uid='11111111-1111-4111-8111-111111111111';`);
const submit=async(alias,a)=> (await db.query('select public.submit_quiz($1,$2::jsonb) as result',[alias,JSON.stringify(a)])).rows[0].result;
const first=await submit('Player A',answers);
assert.equal(first.points,1350);assert.equal(first.correct,11);assert.equal(first.rank,1);assert.equal(first.already_saved,false);
const repeat=await submit('Changed alias',questions.map(q=>({id:q.id,choice:q.replicates,confidence:100})));
assert.equal(repeat.points,1350);assert.equal(repeat.alias,'Player A');assert.equal(repeat.already_saved,true);
await assert.rejects(db.query('select * from quiz_private.scores'),/permission denied/);
await assert.rejects(db.query('update quiz_private.scores set points=1800'),/permission denied/);
await db.exec(`set test.uid='22222222-2222-4222-8222-222222222222';`);
await assert.rejects(submit('Player B',answers.slice(1)),/18 answers/);
await assert.rejects(submit('Player B',answers.map((a,i)=>i===0?{...a,confidence:50.5}:a)),/invalid/);
await assert.rejects(submit('Player B',answers.map((a,i)=>i===0?{...a,confidence:101}:a)),/invalid/);
await assert.rejects(submit('Player B',answers.map((a,i)=>i===0?{...a,choice:'true'}:a)),/invalid/);
await assert.rejects(submit('Player B',[answers[1],answers[0],...answers.slice(2)]),/out of order/);
await assert.rejects(submit('x'.repeat(31),answers),/alias/);
const perfect=await submit('<script>Player B</script>',questions.map(q=>({id:q.id,choice:q.replicates,confidence:100})));
assert.equal(perfect.points,1800);assert.equal(perfect.correct,18);assert.equal(perfect.rank,1);
await db.exec('set role anon;');
await assert.rejects(submit('Anonymous',answers),/permission denied/);
const publicBoard=(await db.query('select public.get_quiz_leaderboard() as result')).rows[0].result;
assert.equal(publicBoard.total,2);assert.equal(publicBoard.entries[0].points,1800);assert.equal(publicBoard.entries[1].rank,2);
assert.ok(!JSON.stringify(publicBoard).includes('11111111'));assert.ok(!JSON.stringify(publicBoard).includes('user_id'));
console.log('PASS: server scoring, first submission retention, validation, ordering, public reads, and private write protection');
await db.close();
